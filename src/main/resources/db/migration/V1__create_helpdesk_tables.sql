CREATE TABLE tickets (
    id UUID PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE ticket_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES tickets(id),
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    CHECK (
        (from_status IS NULL AND to_status = 'OPEN')
        OR (from_status IS NOT NULL AND (
            (from_status = 'OPEN' AND to_status = 'IN_PROGRESS')
            OR (from_status = 'IN_PROGRESS' AND to_status = 'RESOLVED')
        ))
    )
);

CREATE INDEX ticket_status_history_ticket_id_idx ON ticket_status_history (ticket_id, id);
